"""Experiment: aten op census of target models on CPU, joined with tt support status.

Runs each model's forward (+ backward + AdamW step for trainable targets) under a
dispatch logger and writes docs/reference/census.md: op, calls, status on tt.
    python -m kohakutt.bench.models.census
"""

from collections import Counter
from pathlib import Path

import torch
from torch.utils._python_dispatch import TorchDispatchMode
from transformers import LlamaConfig, LlamaForCausalLM, Qwen2Config, Qwen2ForCausalLM

import kohakutt  # noqa: F401  (registers the tt device)
from kohakutt.bench.models.train_check import Block


class OpLogger(TorchDispatchMode):
    """Counts every aten overload dispatched while active."""

    def __init__(self):
        super().__init__()
        self.counts = Counter()

    def __torch_dispatch__(self, func, types, args=(), kwargs=None):
        if func.name().startswith("aten::"):
            self.counts[func.name()] += 1
        return func(*args, **(kwargs or {}))


def hf_config(kind):
    """A small random-weight config of HF model `kind` (no download)."""
    common = dict(
        hidden_size=128,
        intermediate_size=344,
        num_hidden_layers=2,
        num_attention_heads=4,
        num_key_value_heads=2,
        vocab_size=512,
        max_position_embeddings=128,
    )
    return LlamaConfig(**common) if kind == "llama" else Qwen2Config(**common)


def run_training(model, inputs, targets):
    """One forward + cross-entropy + backward + AdamW step."""
    opt = torch.optim.AdamW(model.parameters(), lr=1e-3)
    out = model(inputs)
    logits = out.logits if hasattr(out, "logits") else out
    loss = torch.nn.functional.cross_entropy(logits.flatten(0, -2), targets.flatten())
    loss.backward()
    opt.step()


def census():
    """{target: Counter of aten overloads}."""
    torch.manual_seed(0)
    targets = {}
    tokens = torch.randint(0, 512, (2, 32))

    for name, kind in (("llama (HF)", "llama"), ("qwen2 (HF)", "qwen2")):
        cls = LlamaForCausalLM if kind == "llama" else Qwen2ForCausalLM
        model = cls(hf_config(kind)).bfloat16()
        with OpLogger() as log, torch.no_grad():
            model.generate(tokens[:1, :8], max_new_tokens=4, do_sample=False)
        targets[f"{name} generate"] = log.counts
        with OpLogger() as log:
            run_training(model, tokens, tokens)
        targets[f"{name} train step"] = log.counts

    block = Block().bfloat16()
    with OpLogger() as log:
        run_training(
            block, torch.randn(4, 32, 64).bfloat16(), torch.randint(0, 16, (4, 32))
        )
    targets["transformer block train step"] = log.counts
    return targets


def status(name):
    """kernel / composite / missing for aten overload `name` on tt."""
    has = torch._C._dispatch_has_kernel_for_dispatch_key
    composite = (
        "CompositeImplicitAutograd",
        "CompositeExplicitAutograd",
        "CompositeExplicitAutogradNonFunctional",
    )
    try:
        if has(name, "PrivateUse1"):
            return "kernel"
        if any(has(name, key) for key in composite):
            return "composite"
    except RuntimeError:
        return "unknown"
    return "missing"


def main():
    """Writes docs/reference/census.md."""
    targets = census()
    total = Counter()
    for counts in targets.values():
        total.update(counts)
    lines = [
        "# aten op census",
        "",
        "Generated by `python -m kohakutt.bench.models.census`; ops dispatched by the "
        "targets below on CPU, with their tt status.",
        "",
        "Targets: " + ", ".join(targets) + ".",
        "",
        "| op | calls | targets | tt |",
        "|---|---|---|---|",
    ]
    rows = sorted(total.items(), key=lambda kv: (status(kv[0]) == "kernel", -kv[1]))
    for name, calls in rows:
        used_by = sum(name in counts for counts in targets.values())
        lines.append(f"| `{name}` | {calls} | {used_by} | {status(name)} |")
    missing = [n for n, _ in rows if status(n) == "missing"]
    lines[4] += f" Missing on tt: {len(missing)} of {len(rows)}."
    out = Path("docs/reference/census.md")
    out.write_text("\n".join(lines) + "\n")
    print(out, f"{len(missing)} missing of {len(rows)}:", ", ".join(missing))


if __name__ == "__main__":
    main()
