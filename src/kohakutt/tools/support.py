"""The tt aten support table: every aten operator overload of this torch build.

Status per overload: "kernel" (tt kernel registered), "composite" (a Composite* kernel
decomposes it into other ops, or forwards to their out= form), "missing" (raises on tt).
A composite runs on tt only if the ops it reaches have tt kernels. Overloads specific to
other backends or tensor kinds (cuDNN, MKL-DNN, quantized, sparse, nested, ...) are
grouped as "other backend".
    python -m kohakutt.tools.support [--out docs/reference/aten_support.md]
"""

import argparse
from collections import Counter
from pathlib import Path

import torch

import kohakutt  # noqa: F401  (registers the tt device)

# Kernel source file per op family, for the table's "file" column.
FAMILY = {
    "empty": "factory.cpp",
    "empty_strided": "factory.cpp",
    "copy": "copy.cpp",
    "_copy_from": "copy.cpp",
    "_to_copy": "copy.cpp",
    "add": "binary.cpp",
    "mm": "matmul.cpp",
    "linear": "matmul.cpp",
    "silu": "activation.cpp",
}


def overloads():
    """{qualified overload name (e.g. aten::add.Tensor): tags} of every aten op."""
    found = {}
    for qualified in torch._C._dispatch_get_all_op_names():
        if not qualified.startswith("aten::"):
            continue
        base, _, overload = qualified.removeprefix("aten::").partition(".")
        packet = getattr(torch.ops.aten, base, None)
        op = getattr(packet, overload or "default", None) if packet else None
        if op is not None:
            found[qualified] = op.tags
    return found


def status(name):
    """kernel / composite / missing for aten overload `name` on tt, or None for an
    overload the dispatcher does not know (Python-only aten names)."""
    has = torch._C._dispatch_has_kernel_for_dispatch_key
    try:
        has(name, "PrivateUse1")
    except RuntimeError:
        return None
    if has(name, "PrivateUse1"):
        return "kernel"
    composite = (
        "CompositeImplicitAutograd",
        "CompositeExplicitAutograd",
        "CompositeExplicitAutogradNonFunctional",
    )
    if any(has(name, key) for key in composite):
        return "composite"
    return "missing"


# Name fragments of overloads that belong to other backends or tensor kinds.
OTHER_BACKEND = (
    "cudnn",
    "miopen",
    "mkldnn",
    "mkl_",
    "mps",
    "vulkan",
    "xnnpack",
    "fbgemm",
    "qnnpack",
    "quantize",
    "quantized",
    "q_per_channel",
    "_sparse",
    "sparse_",
    "to_sparse",
    "_nested",
    "nested_",
    "_cufft",
    "cuda",
    "_xpu",
    "onednn",
    "_mtia",
    "_fused_moving",
    "int_repr",
    "fake_quant",
    "_make_per",
    "_saturate_weight",
)


def other_backend(name):
    """True for an overload specific to another backend or tensor kind."""
    base = name.removeprefix("aten::").split(".")[0]
    return any(fragment in base for fragment in OTHER_BACKEND)


def table():
    """Rows (op, core, status, file) for every aten overload the dispatcher knows."""
    rows = []
    for name, tags in sorted(overloads().items()):
        state = status(name)
        if state is None:
            continue
        if state == "missing" and other_backend(name):
            state = "other backend"
        base = name.removeprefix("aten::").split(".")[0].rstrip("_")
        rows.append((name, torch.Tag.core in tags, state, FAMILY.get(base, "")))
    return rows


def render(rows):
    """The Markdown page for `rows`: totals, then every overload by status."""
    counts = Counter((core, state) for _, core, state, _ in rows)
    states = ("kernel", "composite", "missing", "other backend")

    def line(label, core):
        picked = [s for s in states if core is None or (core, s) in counts]
        total = {
            s: sum(n for (c, st), n in counts.items() if st == s and core in (None, c))
            for s in picked
        }
        cells = ", ".join(f"{total[s]} {s}" for s in states if s in total)
        return f"- {label}: {cells} (of {sum(total.values())})"

    lines = [
        "# tt aten support",
        "",
        "Generated by `python -m kohakutt.tools.support`; do not edit by hand.",
        "Every aten operator overload of this torch build, with its status on tt.",
        "",
        line("All aten overloads", None),
        line("Core ATen", True),
        "",
        "| op | core | status | file |",
        "|---|---|---|---|",
    ]
    order = {s: i for i, s in enumerate(states)}
    for name, core, state, file in sorted(rows, key=lambda r: (order[r[2]], r[0])):
        lines.append(f"| `{name}` | {'yes' if core else ''} | {state} | {file} |")
    return "\n".join(lines) + "\n"


def main():
    """Writes the support table."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default="docs/reference/aten_support.md")
    args = parser.parse_args()
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(table()))
    print(out)


if __name__ == "__main__":
    main()
